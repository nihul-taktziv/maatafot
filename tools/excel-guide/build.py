def fmt(v, nf):
    if v is None or v == "":
        return ""
    if isinstance(v, (datetime.datetime, datetime.date)):
        return v.strftime("%m/%Y")
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        if "₪" in nf:
            if round(v) == 0:
                return "-"
            s = f"{abs(v):,.0f} ₪"
            return ("-" if v < 0 else "") + s
        if nf == "0.0":
            return f"{v:.1f}"
        if float(v).is_integer():
            return f"{int(v):,}" if abs(v) >= 1000 else str(int(v))
        return f"{v:,.2f}"
    return str(v)


def sheet_html(name, rows, cols, marks=None, tone=None):
    """Render part of a sheet as an Excel-like table.
    rows: list of row numbers, or "…" for a gap. cols: "B:G".
    marks: {cell: number}. tone: {cell: "ok"|"warn"|"bad"} for conditional colors."""
    marks, tone = marks or {}, tone or {}
    ws, vs = wf[name], wv[name]
    c0, c1 = (column_index_from_string(x) for x in cols.split(":"))
    shown = [r for r in rows if r != "…"]
    merged = {}
    covered = set()
    for mr in ws.merged_cells.ranges:
        if mr.min_col < c0 or mr.min_row not in shown:
            continue
        span_rows = [r for r in range(mr.min_row, mr.max_row + 1)]
        idx = shown.index(mr.min_row)
        rs = 1
        for r in span_rows[1:]:
            if idx + rs < len(shown) and shown[idx + rs] == r and rows[rows.index(mr.min_row) + rs] == r:
                rs += 1
            else:
                break
        cs = min(mr.max_col, c1) - mr.min_col + 1
        merged[(mr.min_row, mr.min_col)] = (rs, cs)
        for r in span_rows[:rs]:
            for c in range(mr.min_col, mr.min_col + cs):
                if (r, c) != (mr.min_row, mr.min_col):
                    covered.add((r, c))
    widths = []
    for c in range(c0, c1 + 1):
        d = ws.column_dimensions.get(get_column_letter(c))
        w = d.width if d is not None and d.width else 10
        widths.append(w)
    total = sum(widths)
    out = [f'<div class="xl"><div class="xl-bar"><span class="xl-file">budget-planning.xlsx</span></div><table class="xl-t"><colgroup><col class="rn">']
    out += [f'<col style="width:{w / total * 100:.2f}%">' for w in widths]
    out.append('</colgroup><tr class="xl-letters"><th></th>' + "".join(f"<th>{get_column_letter(c)}</th>" for c in range(c0, c1 + 1)) + "</tr>")
    for r in rows:
        if r == "…":
            out.append(f'<tr class="xl-gap"><th>⋮</th><td colspan="{c1 - c0 + 1}"></td></tr>')
            continue
        h = ws.row_dimensions[r].height
        style = ' class="tall"' if h and h > 30 else ""
        out.append(f"<tr{style}><th>{r}</th>")
        for c in range(c0, c1 + 1):
            if (r, c) in covered:
                continue
            cell = ws.cell(r, c)
            coord = cell.coordinate
            val = vs[coord].value
            fill = FILL.get(cell.fill.fgColor.rgb if cell.fill.fill_type else "", "")
            cls = [fill] if fill else []
            if cell.font and cell.font.b:
                cls.append("bold")
            if isinstance(val, (int, float)) and not isinstance(val, bool):
                cls.append("num")
                if val < 0:
                    cls.append("neg")
            if isinstance(val, str) and len(val) > 34:
                cls.append("long")
            if coord in tone:
                cls.append("t-" + tone[coord])
            attrs = ""
            if (r, c) in merged:
                rs, cs = merged[(r, c)]
                attrs += (f' rowspan="{rs}"' if rs > 1 else "") + (f' colspan="{cs}"' if cs > 1 else "")
            text = esc(fmt(val, cell.number_format))
            if cell.hyperlink:
                cls.append("link")
            mark = f'<i class="mk">{marks[coord]}</i>' if coord in marks else ""
            out.append(f'<td class="{" ".join(cls)}"{attrs}>{mark}{text}</td>')
        out.append("</tr>")
    out.append("</table>")
    tabs = [ws_.title for ws_ in wf.worksheets]
    out.append('<div class="xl-tabs">' + "".join(f'<span class="{"on" if t == name else ""}">{esc(t)}</span>' for t in tabs) + "</div></div>")
    return "".join(out)


def items(rows):
    """rows: list of (marker or '', title, text)."""
    out = ['<ul class="items">']
    for m, t, d in rows:
        badge = f'<i class="mk">{m}</i>' if m else '<i class="mk dot"></i>'
        out.append(f"<li>{badge}<div><b>{t}</b><span>{d}</span></div></li>")
    out.append("</ul>")
    return "".join(out)


def box(kind, title, body):
    return f'<div class="box {kind}"><b>{title}</b>{body}</div>'


def ul(lines):
    return "<ul class='plain'>" + "".join(f"<li>{x}</li>" for x in lines) + "</ul>"


